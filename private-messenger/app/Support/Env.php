<?php
declare(strict_types=1);

namespace PM\Support;

final class Env
{
    /** @return array<string, string> */
    public static function parseFile(string $file): array
    {
        $out = [];
        foreach (file($file, FILE_IGNORE_NEW_LINES) ?: [] as $line) {
            $line = trim($line);
            if ($line === '' || $line[0] === '#') {
                continue;
            }
            $pos = strpos($line, '=');
            if ($pos === false) {
                continue;
            }
            $key = trim(substr($line, 0, $pos));
            $val = trim(substr($line, $pos + 1));
            if (strlen($val) >= 2 && $val[0] === '"' && str_ends_with($val, '"')) {
                $val = stripcslashes(substr($val, 1, -1));
            }
            if (preg_match('/^[A-Z][A-Z0-9_]*$/', $key)) {
                $out[$key] = $val;
            }
        }
        return $out;
    }

    /** @param array<string, string> $values */
    public static function render(array $values): string
    {
        $lines = ['# Generated by the installer. Keep this file private (chmod 600).'];
        foreach ($values as $k => $v) {
            $lines[] = $k . '="' . addcslashes($v, "\"\\\n\r\t") . '"';
        }
        return implode("\n", $lines) . "\n";
    }
}
